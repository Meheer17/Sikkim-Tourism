/**
 * Get a translation for a specific language and key
 * Returns the key itself as fallback if translation doesn't exist
 */
export function getTranslation(languageCode: string, key: string): string {
  // Prefer the requested language, fall back to English, then to the key
  const lang = translations[languageCode] ?? {};
  return lang[key] ?? translations.en?.[key] ?? key;
}

/**
 * Get all translations for a specific language
 * Returns an empty object if language doesn't exist
 */
export function getLanguageTranslations(languageCode: string): TranslationSet {
  // Return a merged object: English keys as defaults, overridden by requested language
  const base = translations.en ?? {};
  const lang = translations[languageCode] ?? {};
  return { ...base, ...lang } as TranslationSet;
}

/**
 * Check if a language has all required translation keys
 * Useful for validation when adding new languages
 */
export function validateLanguageTranslations(languageCode: string, requiredKeys?: string[]): boolean {
  const lang = translations[languageCode];
  if (!lang) return false;

  if (!requiredKeys) {
    // Validate against English language keys if no required keys provided
    requiredKeys = Object.keys(translations.en);
  }

  return requiredKeys.every((key) => key in lang);
}
